"""Write installer/manifest_defines.iss from a release manifest (tools/gen_release_manifest.py output).

Called by tools/build_installer.cmd. It was an inline `python -c` inside a cmd `if (...)` block, which cmd cannot parse (the first ')' ends the block, and
'%s' / '%d' are batch variable syntax), so the v0.30.0-beta.3 release build failed there.
"""
import json
import sys

NAMES = {'cuda-pack': 'CudaPack', 'wake-word-models': 'WakeWordModels', 'command-model': 'CommandModel', 'gesture-control': 'GestureControl'}


def main(path):
    with open(path, encoding='utf-8') as fh:
        d = json.load(fh)
    by = {c['id']: c for c in d['components']}
    lines = ['; generated by tools\\build_installer.cmd from ' + path + ' -- do not edit']
    lines += ['#define %sSize %d' % (n, by[i]['size_bytes'] or 0) for i, n in NAMES.items() if i in by]
    lines += ['#define %sAvailable %d' % (n, 1 if by[i]['available'] else 0) for i, n in NAMES.items() if i in by]
    lines.append('#define ManifestReleaseTag "%s"' % d['release_tag'])
    with open('installer/manifest_defines.iss', 'w', encoding='ascii', newline='\r\n') as out:
        out.write('\n'.join(lines) + '\n')
    print('installer\\manifest_defines.iss written from', path)


if __name__ == '__main__':
    main(sys.argv[1])
